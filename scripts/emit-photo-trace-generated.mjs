import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { photoTraceWorkerExternals } from './photo-trace-esbuild-externals.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedDir = path.join(repoRoot, 'src', 'logic', 'photo-trace', 'generated');
const workerEntry = path.join(repoRoot, 'src', 'logic', 'photo-trace', 'photo-trace.worker.ts');
const workerOutFile = path.join(generatedDir, 'photo-trace.worker.bundle.js');
const workerCodeTs = path.join(generatedDir, 'photo-trace-worker-code.ts');

/**
 * Bundles the photo worker into a generated TS module so main.js can spawn it
 * from a Blob URL. Obsidian QA installs and obsidian-launcher only copy
 * manifest.json, main.js, and styles.css — not dist/logic/*.
 *
 * `minify` is for production only. The bundle is stored as a string, so the
 * outer main.js minify pass does not shrink this code.
 */
export async function emitPhotoTraceGenerated(options = {}) {
	const minify = options.minify === true;
	fs.mkdirSync(generatedDir, { recursive: true });
	await esbuild.build({
		entryPoints: [workerEntry],
		bundle: true,
		format: 'cjs',
		target: 'es2020',
		outfile: workerOutFile,
		logLevel: 'silent',
		minify,
		external: photoTraceWorkerExternals,
	});
	const workerBundledCode = fs.readFileSync(workerOutFile, 'utf8');
	fs.writeFileSync(
		workerCodeTs,
		`// Generated by scripts/emit-photo-trace-generated.mjs — do not edit.\nexport const photoTraceWorkerBundledCode: string = ${JSON.stringify(workerBundledCode)};\n`,
	);
	fs.rmSync(workerOutFile, { force: true });
}

const isDirectRun =
	process.argv[1] && path.resolve(fileURLToPath(import.meta.url)) === path.resolve(process.argv[1]);
if (isDirectRun) {
	emitPhotoTraceGenerated().catch((error) => {
		console.error(error);
		process.exit(1);
	});
}
